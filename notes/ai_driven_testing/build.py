"""AIドリブンテストの適用範囲：できること・できないこと（一般論のスライドPDF）。

実行: python build.py  → 同じフォルダに ai_driven_testing.pdf を出力
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
from slidekit import (Deck, st, W, M, INK, INK2, INK3, CYAN, CYAN_S, MAG, MAG_S,  # noqa: E402
                      GRN, GRN_S, YEL, YEL_S, BG, PAPER, LINE)

OUT = os.path.join(HERE, "ai_driven_testing.pdf")
FOOT = "autotest-lab ・ AIドリブンテストの適用範囲 一般論のまとめ（2026-11）"
TOTAL = 8
CW = W - 2 * M

d = Deck(OUT, "AIドリブンテストの適用範囲", FOOT, TOTAL)

# 1. 表紙
d.cover("autotest-lab ・ 一般論",
        "AIドリブンテストの適用範囲",
        "できること・できないこと、環境を分ける場合の進め方",
        "AIエージェントにテストの設計・実装・実行まで任せるとき、どこまで任せられるか。"
        "AIが届かない環境のテストをどう進め、どう減らすか。",
        ["公開情報にもとづく一般論。実際の運用は、組織のルールに従うこと。",
         "関連資料：notes/closed_env_ai（閉じた環境でのAIと自動テスト）"])

# 2. 定義
y = d.slide("AIドリブンテストとは", "定義")
d.para("AIエージェントが、テストの<b>設計 → 実装（スクリプト作成）→ 実行 → 結果の分析・報告</b>までを担う進め方。"
       "人は目的と範囲を決め、結果を判断する。", M, y - 4, CW, st(13, INK))
stages = ["計画", "分析・設計", "実装・準備", "実行", "完了・報告"]
who = ["人が決める\n（AIが案を出す）", "AI", "AI", "AI ／ 環境しだい", "AI ＋ 人が判断"]
fills = [BG, CYAN_S, CYAN_S, YEL_S, CYAN_S]
sw = (CW - 4 * 22) / 5; sy = y - 70
for i, s in enumerate(stages):
    x = M + i * (sw + 22)
    d.box(x, sy, sw, 44, fill=INK)
    d.para(s, x + 6, sy - 13, sw - 12, st(13, PAPER, align=1))
    d.box(x, sy - 52, sw, 60, fill=fills[i])
    d.para(who[i].replace("\n", "<br/>"), x + 6, sy - 64, sw - 12, st(11.5, INK, align=1))
    if i < 4:
        d.arrow(x + sw + 3, sy - 22, x + sw + 19, sy - 22)
d.box(M, sy - 140, CW, 66, fill=YEL_S, accent=YEL)
d.para("<b>分かれ目は「実行」</b>：AIエージェントが動く環境から、テスト対象に<b>直接届く</b>なら最後まで任せられる。"
       "届かない環境（サポートの切れたOS、隔離されたネットワーク上の機器など）では、"
       "AIは「準備まで」と「結果の分析」を担い、実行は別の手段になる。",
       M + 20, sy - 154, CW - 40, st(12.5, INK))
d.end()

# 3. 3つの区分
y = d.slide("任せられる範囲は3つに分かれる", "全体像")
cw = (CW - 2 * 18) / 3
cards = [
    ("A. 最後まで任せられる",
     "AIの環境から対象に届く。<br/><br/>"
     "・テスト環境のWebアプリ、API<br/>・AIの環境と同じ、サポート中のOS上のアプリ<br/>"
     "・エミュレーター、シミュレーター<br/>・クラウドの端末・ブラウザ<br/>・仮想の機器（シミュレーター）との通信", GRN, GRN_S),
    ("B. 準備まで任せ、実行は分ける",
     "AIの環境から対象に届かない。<br/><br/>"
     "・サポートの切れた古いOS（通常のネットワークにつなげない）<br/>"
     "・テスト用LANにつないだ開発中の機器<br/>・社外に出せないデータを使う環境<br/>"
     "・ネットにつながらない現場の環境", YEL, YEL_S),
    ("C. 人が担う",
     "AIが判断や操作をしにくい。<br/><br/>"
     "・見た目や使い心地の評価<br/>・物理的な操作と確認（ケーブル、用紙、電源など）<br/>"
     "・安全や法規に関わる最終判断<br/>・リリースの可否の承認", MAG, MAG_S),
]
for i, (h, b, a, f) in enumerate(cards):
    d.card(M + i * (cw + 18), y - 4, cw, 240, h, b, accent=a, fill=f, head_size=15, body_size=11.5)
d.para("Cの多くも、AIが手順書・確認項目・記録の整理を作れる。人は「見る・触る・決める」に集中する。",
       M, y - 260, CW, st(12, INK2))
d.end()

# 4. ケース別の表
y = d.slide("ケース別：AIの範囲と実行のしかた", "整理")
hdr = ["ケース", "なぜ分けるか", "AIの範囲", "実行のしかた"]
wid = [180, 230, 200, 254]
rows = [hdr,
        ["サポート中のOS上のアプリ", "—", "設計〜実行〜報告", "AIの環境で直接実行"],
        ["Web・API（テスト環境）", "—", "設計〜実行〜報告", "AIの環境から接続して実行"],
        ["サポートの切れたOS", "通常のネットワークにつなげない。新しいツールが動かないこともある",
         "設計・実装・結果の分析", "分離した環境で実行（持ち込み）"],
        ["テスト用LAN上の開発中の機器", "開発中の機器を通常のネットワークから隔離する",
         "設計・実装・結果の分析", "テスト用LANにつながるPCで実行"],
        ["物理的な操作を含むテスト", "人の手や目が要る", "手順書・確認項目・記録の整理", "人が実施し、AIが記録を整理"],
        ["見た目・使い心地", "正解が数値で決まらない", "観点の洗い出し・比較の補助", "人が評価"],
        ]
d.table(rows, M, y, wid, size=10.5)
d.end()

# 5. 分離が必要なときの手段
y = d.slide("環境を分けるときの手段", "進め方")
hdr = ["手段", "流れ", "手間", "注意"]
wid = [180, 360, 60, 264]
rows = [hdr,
        ["① 手動で持ち込む", "AIがスクリプトと手順を作る → 人がコピーして実行 → 結果を持ち帰り、AIが分析",
         "大", "すぐ始められる。往復のたびに人手がかかる"],
        ["② 実行係を置く", "分離した環境に「決まった手順だけ実行する係」を置き、承認された受け渡し口でスクリプトと結果をやりとり",
         "中", "受け渡し口の設け方は組織のルールしだい"],
        ["③ AIを中に置く", "分離した環境の中にローカルLLMを置き、実行と分析をその場で行う",
         "中〜大", "GPUマシンとモデルの持ち込みが要る。精度はクラウドより低い"],
        ["④ 両方につながる中継", "AIの環境と分離した環境の両方につながるマシンを置く",
         "小", "隔離の意味が薄れるため、許されないことが多い"],
        ]
h = d.table(rows, M, y, wid, size=10.5)
d.para("どの手段でも共通：スクリプトは実行時にAIを使わない普通のコードにし、失敗の証拠（スクリーンショット、部品の木、操作ログ）を厚く取る。"
       "詳しくは「閉じた環境でのAIと自動テスト」を参照。",
       M, y - h - 14, CW, st(11.5, INK2))
d.end()

# 6. 分離環境のテストを減らす
y = d.slide("分離した環境でのテストを減らす", "進め方")
d.box(M, y - 4, CW, 50, fill=GRN_S, accent=GRN)
d.para("<b>考え方</b>：OSや環境によって結果が変わる部分だけを、分離した環境で確かめる。それ以外はAIの環境で厚く回す。",
       M + 18, y - 18, CW - 34, st(12.5, INK))
bw = (CW - 20) / 2
tips = [
    ("OSで差が出る部分を見極める", "インストール、ドライバ、通信、ファイルの扱い、画面の描画などはOSで差が出やすい。"
     "画面の流れや業務の判定は差が出にくい。差が出にくい部分は1つのOSで確かめれば足りる。"),
    ("組み合わせを絞る", "OS×機器×設定の全部ではなく、2つずつの組み合わせを網羅する方法（ペアワイズ）や、"
     "利用の多い構成を優先して件数を減らす。"),
    ("仮想の機器と仮想マシンを使う", "通信の手順は仮想の機器（シミュレーター）でAIの環境から確かめる。"
     "古いOSは仮想マシンにすれば準備と復元が速い（置き場所は組織のルールしだい）。"),
    ("サポートの方針を決める", "サポートの切れたOSで、どこまで確かめるかを方針として決める"
     "（例：代表的な操作の確認だけにする）。"),
]
for i, (hd, bd) in enumerate(tips):
    r, col = divmod(i, 2)
    d.card(M + col * (bw + 20), y - 70 - r * 140, bw, 126, hd, bd, accent=CYAN, fill=CYAN_S,
           head_size=14, body_size=11)
d.end()

# 7. 配分のイメージ
y = d.slide("テストの配分のイメージ", "進め方")
layers = [
    ("AIの環境（A）", "設計・実装・実行・分析をAIが回す。件数の大半はここ。新しい機能や画面の変更にすぐ追従する",
     CW, GRN, GRN_S),
    ("分離した環境（B）", "OSや機器で差が出る部分の代表的な確認。AIが作ったスクリプトを持ち込み、証拠を持ち帰る",
     CW * 0.68, YEL, YEL_S),
    ("人（C）", "見た目・物理的な確認・最終判断", CW * 0.4, MAG, MAG_S),
]
ly = y - 10
for i, (hd, bd, w, a, f) in enumerate(layers):
    x = M + (CW - w) / 2
    d.box(x, ly - i * 72, w, 60, fill=f, accent=a)
    d.para("<b>%s</b>　%s" % (hd, bd), x + 20, ly - i * 72 - 14, w - 40, st(12, INK))
d.para("帯の幅は件数の多さのイメージ。上の帯ほどAIに任せる量が多い。",
       M, ly - 230, CW, st(11.5, INK3))
d.end()

# 8. まとめ
y = d.slide("まとめと、先に確かめること", "まとめ")
pts = [
    "AIドリブンテストの分かれ目は「実行」。AIの環境から対象に届くなら最後まで任せられる。",
    "届かない環境（古いOS、テスト用LANの機器など）は、AIが準備と分析を担い、実行は持ち込みで行う。",
    "分離した環境のテストは、OSや機器で差が出る部分に絞って減らす。それ以外はAIの環境で厚く回す。",
]
for i, p in enumerate(pts):
    d.box(M, y - 4 - i * 72, CW, 60, fill=BG, accent=CYAN)
    d.para(p, M + 22, y - 24 - i * 72, CW - 44, st(13, INK))
d.box(M, y - 226, CW, 90, fill=YEL_S, accent=YEL)
d.para("<b>先に確かめること（組織のルールしだい）</b><br/>"
       "・分離した環境への持ち込み・持ち出しの手段　・古いOSを仮想マシンで動かしてよいか<br/>"
       "・テスト用LANにつなげてよいマシンの条件　・ローカルLLMやモデルの持ち込みの可否",
       M + 20, y - 238, CW - 40, st(12, INK))
d.end()

d.save()
print(OUT)
